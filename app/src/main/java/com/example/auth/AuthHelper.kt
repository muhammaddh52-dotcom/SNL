private const val TAG = "Auth"

/**
 * Holds registration details entered by a new Dealer or Distributor on the Registration screen
 * so they can be automatically applied once Firebase Authentication completes.
 */
data class PendingRegistrationDraft(
    val email: String = "",
    val fullName: String = "",
    val businessName: String = "",
    val phone: String = "+92 3",
    val city: String = "Karachi",
    val address: String = "",
    val role: String = "DEALER"
)

object PendingRegistrationStore {
    private val _draft = MutableStateFlow<PendingRegistrationDraft?>(null)
    val draft: StateFlow<PendingRegistrationDraft?> = _draft.asStateFlow()

    fun saveDraft(draft: PendingRegistrationDraft) {
        _draft.value = draft
    }

    fun clearDraft() {
        _draft.value = null
    }
}

internal fun FirebaseAuth.authStateFlow(): Flow<FirebaseUser?> = callbackFlow {
    val listener = FirebaseAuth.AuthStateListener { auth ->
        trySend(auth.currentUser)
    }
    addAuthStateListener(listener)
    awaitClose { removeAuthStateListener(listener) }
}

fun attemptAutoSignIn(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onUnauthenticated: () -> Unit,
    scope: CoroutineScope
) {
    if (Firebase.auth.currentUser != null) {
        onAuthSuccess()
        return
    }
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (e: Exception) {
        onUnauthenticated()
        return
    }

    val googleIdOption = GetGoogleIdOption.Builder()
        .setFilterByAuthorizedAccounts(true)
        .setServerClientId(clientId)
        .setAutoSelectEnabled(true)
        .build()

    // One option per request for API 36 Credential Manager bottom-sheet responsiveness
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(googleIdOption)
        .build()

    scope.launch {
        try {
            val result = credentialManager.getCredential(context, request)
            val credential = result.credential
            if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                Firebase.auth.signInWithCredential(authCredential).await()
                onAuthSuccess()
            } else {
                onUnauthenticated()
            }
        } catch (e: Exception) {
            onUnauthenticated()
        }
    }
}

fun onGoogleSignInClicked(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onAuthError: (String) -> Unit,
    scope: CoroutineScope,
    onAuthCancelled: () -> Unit = {}
) {
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (e: Exception) {
        onAuthError("Google Sign-In configuration missing: default_web_client_id not found")
        return
    }

    // Exclusively use GetSignInWithGoogleOption in interactive sign-in request
    val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(signInOption)
        .build()

    scope.launch {
        try {
            val activityContext = (context as? Activity) ?: context
            val result = credentialManager.getCredential(activityContext, request)
            val credential = result.credential
            if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                Firebase.auth.signInWithCredential(authCredential).await()
                onAuthSuccess()
            } else {
                onAuthError("Unexpected credential type")
            }
        } catch (e: GetCredentialCancellationException) {
            Log.w(TAG, "Google Sign-In cancelled or dismissed: ${e.message}", e)
            onAuthCancelled()
        } catch (e: Exception) {
            Log.e(TAG, "Google Sign-In failed", e)
            onAuthError(e.localizedMessage ?: "Sign in failed")
        }
    }
}

/**
 * Triggers a Firebase Authentication password reset email for the specified address.
 */
fun sendFirebasePasswordReset(
    email: String,
    scope: CoroutineScope,
    onSuccess: (String) -> Unit,
    onError: (String) -> Unit
) {
    val trimmedEmail = email.trim()
    if (trimmedEmail.isBlank() || !trimmedEmail.contains("@")) {
        onError("Please enter a valid registered email address.")
        return
    }
    scope.launch {
        try {
            Firebase.auth.sendPasswordResetEmail(trimmedEmail).await()
            onSuccess("Password reset instructions have been sent to $trimmedEmail via Firebase Authentication.")
        } catch (e: Exception) {
            Log.w(TAG, "Password reset request notice for $trimmedEmail: ${e.message}")
            // Provide actionable B2B guidance if the account is federated with Google Sign-In
            onSuccess(
                "Password recovery initiated for $trimmedEmail. If your account uses Google Sign-In, you can also sign in directly with Google or contact SNL Admin (+92 310 100 52 53)."
            )
        }
    }
}

fun signOut(
    credentialManager: CredentialManager,
    scope: CoroutineScope,
    onSignOutComplete: () -> Unit = {}
) {
    scope.launch {
        withContext(NonCancellable) {
            try {
                credentialManager.clearCredentialState(ClearCredentialStateRequest())
            } catch (e: Exception) {
                Log.w(TAG, "Failed to clear credential state: ${e.message}")
            } finally {
                Firebase.auth.signOut()
                onSignOutComplete()
            }
        }
    }
}
